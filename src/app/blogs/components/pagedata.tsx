/* ---------- lookups (O(1) by slug, built once at module load) ---------- */

const articleMap = new Map(articles.map((a, i) => [a.slug, { article: a, index: i }]));

export const getArticle = (slug: string) => articleMap.get(slug)?.article;

/** The next `count` stories after `slug` (wraps around) – stable between builds. */
export const getRelatedArticles = (slug: string, count = 3) => {
  const entry = articleMap.get(slug);
  if (!entry) return [];
  const n = Math.min(count, articles.length - 1);
  return Array.from({ length: n }, (_, i) => articles[(entry.index + 1 + i) % articles.length]);
};
